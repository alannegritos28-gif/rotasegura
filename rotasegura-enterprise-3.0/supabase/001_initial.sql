create or replace function public.is_member(org uuid) returns boolean language sql stable security definer set search_path=public as $$
 select exists(select 1 from public.memberships m where m.organization_id=org and m.user_id=auth.uid());
$$;
create or replace function public.has_role(org uuid, roles public.member_role[]) returns boolean language sql stable security definer set search_path=public as $$
 select exists(select 1 from public.memberships m where m.organization_id=org and m.user_id=auth.uid() and m.role=any(roles));
$$;

create policy "profile self" on public.profiles for all using(id=auth.uid()) with check(id=auth.uid());
create policy "org members read" on public.organizations for select using(public.is_member(id));
create policy "members see memberships" on public.memberships for select using(public.is_member(organization_id));
create policy "admins manage vehicles" on public.vehicles for all using(public.is_member(organization_id)) with check(public.has_role(organization_id,array['owner','admin','dispatcher']::public.member_role[]));
create policy "members read drivers" on public.drivers for select using(public.is_member(organization_id));
create policy "admins manage drivers" on public.drivers for all using(public.has_role(organization_id,array['owner','admin','dispatcher']::public.member_role[])) with check(public.has_role(organization_id,array['owner','admin','dispatcher']::public.member_role[]));
create policy "members read trips" on public.trips for select using(public.is_member(organization_id));
create policy "dispatch manage trips" on public.trips for all using(public.has_role(organization_id,array['owner','admin','dispatcher']::public.member_role[])) with check(public.has_role(organization_id,array['owner','admin','dispatcher']::public.member_role[]));
create policy "authenticated read confirmed incidents" on public.incidents for select to authenticated using(status in ('Confirmada','Monitorada') or reporter_id=auth.uid() or (organization_id is not null and public.is_member(organization_id)));
create policy "authenticated report incidents" on public.incidents for insert to authenticated with check(source='COMUNIDADE' and reporter_id=auth.uid());
create policy "own confirmations" on public.incident_confirmations for all to authenticated using(user_id=auth.uid()) with check(user_id=auth.uid());
create policy "org audit read admins" on public.audit_log for select using(organization_id is not null and public.has_role(organization_id,array['owner','admin']::public.member_role[]));

