create extension if not exists pgcrypto;
create extension if not exists postgis;

create type public.member_role as enum ('owner','admin','dispatcher','driver','viewer');
create type public.incident_status as enum ('Em validação','Monitorada','Confirmada','Descartada');
create type public.incident_source as enum ('OFICIAL','COMUNIDADE');
create type public.severity_level as enum ('baixa','media','alta');

create table public.organizations (
 id uuid primary key default gen_random_uuid(),
 name text not null,
 created_at timestamptz not null default now()
);
create table public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 full_name text,
 phone text,
 created_at timestamptz not null default now()
);
create table public.memberships (
 organization_id uuid not null references public.organizations(id) on delete cascade,
 user_id uuid not null references auth.users(id) on delete cascade,
 role public.member_role not null default 'viewer',
 created_at timestamptz not null default now(),
 primary key (organization_id,user_id)
);
create table public.vehicles (
 id uuid primary key default gen_random_uuid(),
 organization_id uuid not null references public.organizations(id) on delete cascade,
 plate text not null,
 model text not null,
 axles integer,
 gross_weight_kg integer,
 height_m numeric(5,2),
 width_m numeric(5,2),
 length_m numeric(6,2),
 status text not null default 'Disponível',
 created_at timestamptz not null default now(),
 unique(organization_id,plate)
);
create table public.drivers (
 id uuid primary key default gen_random_uuid(),
 organization_id uuid not null references public.organizations(id) on delete cascade,
 user_id uuid references auth.users(id) on delete set null,
 name text not null,
 cnh_hash text,
 phone text,
 active boolean not null default true,
 created_at timestamptz not null default now()
);
create table public.trips (
 id uuid primary key default gen_random_uuid(),
 organization_id uuid not null references public.organizations(id) on delete cascade,
 vehicle_id uuid references public.vehicles(id) on delete set null,
 driver_id uuid references public.drivers(id) on delete set null,
 origin_label text not null,
 destination_label text not null,
 origin geography(point,4326),
 destination geography(point,4326),
 planned_route geometry(linestring,4326),
 status text not null default 'Planejada',
 risk_score numeric(7,2) default 0,
 started_at timestamptz,
 finished_at timestamptz,
 created_at timestamptz not null default now()
);
create table public.incidents (
 id uuid primary key default gen_random_uuid(),
 organization_id uuid references public.organizations(id) on delete set null,
 reporter_id uuid references auth.users(id) on delete set null,
 type text not null,
 road text not null,
 place text,
 description text not null,
 lat double precision,
 lon double precision,
 location geography(point,4326) generated always as (case when lat is null or lon is null then null else st_setsrid(st_makepoint(lon,lat),4326)::geography end) stored,
 severity public.severity_level not null default 'media',
 source public.incident_source not null default 'COMUNIDADE',
 status public.incident_status not null default 'Em validação',
 official_source text,
 official_reference text,
 confirmations integer not null default 0 check(confirmations >= 0),
 updated text default 'agora',
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
create index incidents_location_gix on public.incidents using gist(location);
create index trips_route_gix on public.trips using gist(planned_route);
create index incidents_status_idx on public.incidents(status,created_at desc);

create table public.incident_confirmations (
 incident_id uuid not null references public.incidents(id) on delete cascade,
 user_id uuid not null references auth.users(id) on delete cascade,
 confirmation boolean not null,
 created_at timestamptz not null default now(),
 primary key(incident_id,user_id)
);
create table public.audit_log (
 id bigint generated by default as identity primary key,
 organization_id uuid references public.organizations(id) on delete set null,
 actor_id uuid references auth.users(id) on delete set null,
 action text not null,
 entity_type text not null,
 entity_id text,
 metadata jsonb not null default '{}'::jsonb,
 created_at timestamptz not null default now()
);

