end $$;

-- First-login corporate bootstrap. The signup page sends full_name + organization_name metadata.
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path=public as $$
declare org_id uuid; org_name text; base_slug text;
begin
 insert into public.profiles(id,full_name) values(new.id,coalesce(new.raw_user_meta_data->>'full_name',split_part(new.email,'@',1))) on conflict(id) do nothing;
 org_name:=nullif(trim(new.raw_user_meta_data->>'organization_name'),'');
 if org_name is not null then
   base_slug:=lower(regexp_replace(unaccent(org_name),'[^a-zA-Z0-9]+','-','g'));
   insert into public.organizations(name,slug) values(org_name,base_slug||'-'||left(replace(new.id::text,'-',''),6)) returning id into org_id;
   insert into public.memberships(organization_id,user_id,role) values(org_id,new.id,'owner');
 end if;
 return new;
end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();

