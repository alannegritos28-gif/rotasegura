-- Transactional trip creation from GeoJSON, keeping PostGIS conversion inside PostgreSQL.
create or replace function public.create_trip(
 p_origin_label text,p_destination_label text,p_origin_lon double precision,p_origin_lat double precision,
 p_destination_lon double precision,p_destination_lat double precision,p_route_geojson jsonb,
 p_distance_km numeric,p_duration_min integer,p_risk_score numeric,p_risk_level text,p_provider text,
 p_vehicle_id uuid default null,p_driver_id uuid default null
) returns uuid language plpgsql security definer set search_path=public as $$
declare org_id uuid; new_id uuid;
begin
 select organization_id into org_id from public.memberships where user_id=auth.uid() and role in ('owner','admin','dispatcher') limit 1;
 if org_id is null then raise exception 'forbidden'; end if;
 insert into public.trips(organization_id,vehicle_id,driver_id,origin_label,destination_label,origin,destination,planned_route,status,risk_score,risk_level,distance_km,duration_min,route_provider,metadata)
 values(org_id,p_vehicle_id,p_driver_id,p_origin_label,p_destination_label,
 st_setsrid(st_makepoint(p_origin_lon,p_origin_lat),4326)::geography,
 st_setsrid(st_makepoint(p_destination_lon,p_destination_lat),4326)::geography,
 st_setsrid(st_geomfromgeojson(p_route_geojson::text),4326),'Planejada',p_risk_score,p_risk_level,p_distance_km,p_duration_min,p_provider,jsonb_build_object('created_by',auth.uid()))
 returning id into new_id;
 return new_id;
end $$;
grant execute on function public.create_trip(text,text,double precision,double precision,double precision,double precision,jsonb,numeric,integer,numeric,text,text,uuid,uuid) to authenticated;
