-- Atomic confirmation + confidence recalculation
create or replace function public.confirm_incident(p_incident uuid,p_confirm boolean default true)
returns void language plpgsql security definer set search_path=public as $$
begin
 if auth.uid() is null then raise exception 'unauthenticated'; end if;
 insert into public.incident_confirmations(incident_id,user_id,confirmation) values(p_incident,auth.uid(),p_confirm)
 on conflict(incident_id,user_id) do update set confirmation=excluded.confirmation,created_at=now();
 update public.incidents i set confirmations=(select count(*) from public.incident_confirmations c where c.incident_id=i.id and c.confirmation=true),updated_at=now() where i.id=p_incident;
end $$;
grant execute on function public.confirm_incident(uuid,boolean) to authenticated;

-- Read-only RPC for nearby active risks used by routing services.
create or replace function public.nearby_incidents(p_lon double precision,p_lat double precision,p_radius_m integer default 10000)
returns setof public.incidents language sql stable security definer set search_path=public as $$
 select * from public.incidents where location is not null and status in ('Confirmada','Monitorada','Em validação')
 and st_dwithin(location,st_setsrid(st_makepoint(p_lon,p_lat),4326)::geography,p_radius_m)
 order by created_at desc limit 200;
$$;
grant execute on function public.nearby_incidents(double precision,double precision,integer) to authenticated;

